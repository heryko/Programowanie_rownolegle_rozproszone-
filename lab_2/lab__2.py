import time
import matplotlib.pyplot as plt
import numpy as np
import cupy as cp
import pycuda.autoinit
import pycuda.driver as cuda
from pycuda.compiler import SourceModule

kernel_code = """
__global__ void matrixMul(float *A, float *B, float *C, int N) {
    int row = blockIdx.y * blockDim.y + threadIdx.y;
    int col = blockIdx.x * blockDim.x + threadIdx.x;
    float sum = 0.0;
    if(row < N && col < N) {
        for (int k = 0; k < N; k++) {
            sum += A[row * N + k] * B[k * N + col];
        }
        C[row * N + col] = sum;
    }
}
"""

mod = SourceModule(kernel_code)
matrixMul = mod.get_function("matrixMul")

sizes = [1024, 2048, 4096, 8192]
times_cpu = []
times_gpu = []
times_cupy = []

for N in sizes:
    A_cpu = np.random.randn(N, N).astype(np.float32)
    B_cpu = np.random.randn(N, N).astype(np.float32)
    C_cpu = np.empty((N, N), dtype=np.float32)

    # CPU
    start_cpu = time.time()
    C_expected = np.dot(A_cpu, B_cpu)
    times_cpu.append(time.time() - start_cpu)

    # GPU PyCUDA
    A_gpu = cuda.mem_alloc(A_cpu.nbytes)
    B_gpu = cuda.mem_alloc(B_cpu.nbytes)
    C_gpu = cuda.mem_alloc(C_cpu.nbytes)

    cuda.memcpy_htod(A_gpu, A_cpu)
    cuda.memcpy_htod(B_gpu, B_cpu)

    block_size = (32, 32, 1)
    grid_size = (int(np.ceil(N / 32)), int(np.ceil(N / 32)), 1)

    cuda.Context.synchronize()
    start_gpu = time.time()
    matrixMul(
        A_gpu, B_gpu, C_gpu, np.int32(N), block=block_size, grid=grid_size
    )
    cuda.Context.synchronize()
    times_gpu.append(time.time() - start_gpu)

    gpu_time = time.time() - start_gpu
    cpu_time = time.time() - start_cpu
    del A_gpu
    del B_gpu
    del C_gpu

    print(f"N = {N:5d} | CPU: {cpu_time:8.8f} s | PyCUDA: {gpu_time:8.8f} s")

for N in sizes:
    A_cpu = np.random.randn(N, N).astype(np.float32)
    B_cpu = np.random.randn(N, N).astype(np.float32)

    A_cupy = cp.asarray(A_cpu)
    B_cupy = cp.asarray(B_cpu)

    cp.cuda.Stream.null.synchronize()
    start_cupy = time.time()
    C_cupy = cp.dot(A_cupy, B_cupy)
    cp.cuda.Stream.null.synchronize()
    times_cupy.append(time.time() - start_cupy)
    cupy_time = time.time() - start_cupy

    print(f"N = {N:5d} | CuPy: {cupy_time:8.8f} s")

plt.figure(figsize=(10, 6))
plt.plot(sizes, times_cpu, label="CPU (Numpy)", marker="o")
plt.plot(sizes, times_gpu, label="GPU (PyCUDA)", marker="s")
plt.plot(sizes, times_cupy, label="GPU (Cupy)", marker="^")
plt.legend()
plt.xlabel("N")
plt.ylabel("[s]")
plt.title("CPU vs PyCUDA vs CuPy")
plt.grid(True)
plt.show()